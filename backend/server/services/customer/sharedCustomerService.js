'use strict';

const ApiError = require('../../utils/apiError');
const User = require('../../models/userModel');
const { isValidPhone } = require('../../utils/validators/phoneValidator');
const { normalizeEgyptianPhone } = require('../../utils/crm/phone');

// The SHARED customer record (QA U1 / B5): customers are User documents with role 'user' - the same
// records ERP Sales/Purchase already use (customerController.js#createCustomer) - never a second,
// Commercial- or CRM-only customer collection. This service adds two things the ERP-permissioned
// /customers endpoints can't give a Commercial-only user or the CRM handoff:
//   - a phone-aware lookup that recognizes the same number in its different stored spellings
//     ("01211892995", "+201211892995", "201211892995"), so a lead's customer is never duplicated;
//   - find-or-create with exactly the ERP's own rules (name + valid phone, phone unique,
//     customerNumber always server-generated by the model's pre-save hook).

const escapeRegex = s => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Every stored spelling an Egyptian number may appear under. */
function phoneVariants(phone) {
  const raw = String(phone || '').trim();
  if (!raw) return [];
  const out = new Set([raw]);
  const e164 = normalizeEgyptianPhone(raw);
  if (e164) {
    const national = `0${e164.slice(3)}`; // +201211892995 -> 01211892995
    out.add(e164);
    out.add(e164.slice(1)); // 201211892995
    out.add(national);
  }
  return [...out];
}

async function findCustomerByPhone(phone) {
  const variants = phoneVariants(phone);
  if (!variants.length) return null;
  return User.findOne({ role: 'user', isDeleted: { $ne: true }, $or: [{ phone: { $in: variants } }, { additionalPhone: { $in: variants } }] }).select('_id name email phone customerNumber').lean();
}

async function searchCustomers(keyword = '', limit = 10) {
  const filter = { role: 'user', isDeleted: { $ne: true } };
  const k = String(keyword || '').trim().slice(0, 100);
  if (k) {
    const rx = new RegExp(escapeRegex(k), 'i');
    filter.$or = [{ name: rx }, { email: rx }, { phone: { $in: phoneVariants(k) } }, { phone: rx }];
    if (/^\d+$/.test(k)) filter.$or.push({ customerNumber: Number(k) }); // customerNumber is numeric
  }
  return User.find(filter).select('_id name email phone customerNumber').sort({ name: 1 }).limit(Math.min(Math.max(limit, 1), 25)).lean();
}

/**
 * Finds the shared customer for a phone, or creates one. Matching is by phone only (the ERP's own
 * uniqueness rule) - a different person with the same name is never merged into an existing
 * customer. Email is only stored when no other user already holds it (User.email is unique).
 */
async function findOrCreateCustomer({ name, phone, email }, { createdBy = null } = {}) {
  const cleanName = String(name || '').trim().slice(0, 150);
  if (!cleanName) throw new ApiError('Customer name is required.', 400);
  const cleanPhone = String(phone || '').trim();
  if (!cleanPhone || !isValidPhone(cleanPhone)) throw new ApiError('A valid customer phone number is required.', 400);

  const existing = await findCustomerByPhone(cleanPhone);
  if (existing) return { customer: existing, created: false };

  const storedPhone = normalizeEgyptianPhone(cleanPhone) ? `0${normalizeEgyptianPhone(cleanPhone).slice(3)}` : cleanPhone;
  let safeEmail;
  if (email) {
    const e = String(email).trim().toLowerCase();
    if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(e) && !(await User.exists({ email: e }))) safeEmail = e;
  }
  try {
    const customer = await User.create({ name: cleanName, phone: storedPhone, email: safeEmail, role: 'user', isOffline: true, type: 'offline', createdBy: createdBy || undefined });
    return { customer: { _id: customer._id, name: customer.name, email: customer.email, phone: customer.phone, customerNumber: customer.customerNumber }, created: true };
  } catch (err) {
    if (err?.code === 11000) {
      // Lost a race to a concurrent creation for the same phone - use the winner.
      const winner = await findCustomerByPhone(cleanPhone);
      if (winner) return { customer: winner, created: false };
    }
    throw err;
  }
}

module.exports = { phoneVariants, findCustomerByPhone, searchCustomers, findOrCreateCustomer };
